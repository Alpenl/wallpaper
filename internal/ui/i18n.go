func mediaNote(lang, note string) string {
	if !strings.HasPrefix(lang, "en") {
		return note
	}
	var parts []string
	changed := false
	for rest := note; rest != ""; {
		matched := false
		for _, message := range mediaNoteMessages {
			if rest == message || strings.HasPrefix(rest, message+"；") {
				parts = append(parts, translate(lang, message))
				rest = strings.TrimPrefix(strings.TrimPrefix(rest, message), "；")
				matched, changed = true, true
				break
			}
		}
		if matched {
			continue
		}
		part, remaining, _ := strings.Cut(rest, "；")
		for _, p := range mediaNotePatterns {
			if p.pattern.MatchString(part) {
				part = p.pattern.ReplaceAllString(part, p.replacement)
				changed = true
				break
			}
		}
		parts, rest = append(parts, part), remaining
	}
	if !changed {
		return note
	}
	return strings.Join(parts, "; ")
}
